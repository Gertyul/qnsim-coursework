// тривалість прогону за критерієм (3.1) з ε1 = 3 хв
function T1() {
  const rows = readCsv("transient.csv").slice(1);
  const sp = rows.map((x) => Number(x[x.length - 1]));
  for (let i = 0; i < rows.length; i++) if (sp.slice(i).every((v) => v < 3.0)) return Number(rows[i][0]);
  return Number(rows[rows.length - 1][0]);
}

// однофакторний дисперсійний аналіз за priorities.csv для заданих рівнів
function anova3(levels) {
  const rows = readCsv("priorities.csv").slice(1);
  const data = levels.map((lv) => rows.filter((x) => x[0] === lv).map((x) => Number(x[2])));
  const q = data.length, pp = data[0].length;
  const mean = (a) => a.reduce((s, v) => s + v, 0) / a.length;
  const mj = data.map(mean), gm = mean(mj);
  const Df = pp * mj.reduce((s, m) => s + (m - gm) ** 2, 0) / (q - 1);
  const Dr = data.reduce((s, d, j) => s + d.reduce((ss, v) => ss + (v - mj[j]) ** 2, 0), 0) / (q * (pp - 1));
  return { Df, Dr, F: Df / Dr, df1: q - 1, df2: q * (pp - 1) };
}

