// n-те входження def name у файлі (з урахуванням відступу)
function extractDef(rel, name, nth = 1) {
  const lines = fs.readFileSync(path.join(ROOT, rel), "utf8").split("\n");
  let cnt = 0, i = -1;
  for (let k = 0; k < lines.length; k++) {
    if (new RegExp(`^\\s*def ${name}\\(`).test(lines[k]) && ++cnt === nth) { i = k; break; }
  }
  if (i < 0) throw new Error("no def " + name);
  const ind = lines[i].match(/^\s*/)[0].length;
  let j = i + 1;
  while (j < lines.length && (!lines[j].trim() || lines[j].match(/^\s*/)[0].length > ind ||
         lines[j].trim().startsWith(")"))) j++;
  while (!lines[j - 1].trim()) j--;
  return lines.slice(i, j).map((l) => l.slice(ind)).join("\n");
}

