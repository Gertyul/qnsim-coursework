function readCsv(name) {
  const t = fs.readFileSync(path.join(ROOT, "results", name), "utf8").trim().split("\n");
  return t.map((l) => {
    const out = []; let cur = "", q = false;
    for (const ch of l) {
      if (ch === '"') q = !q; else if (ch === "," && !q) { out.push(cur); cur = ""; } else cur += ch;
    }
    out.push(cur.replace(/\r$/, ""));
    return out;
  });
}
